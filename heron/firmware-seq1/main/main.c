/* ------------------------------------------------------------------ */
/* Frame geometry                                                      */
/* ------------------------------------------------------------------ */
#define FRAME_W        1024
#define FRAME_H        600
#define FRAME_STRIDE   (FRAME_W * 2)              /* RGB565 bytes per row */
#define FRAME_BYTES    (FRAME_W * FRAME_H * 2)    /* 1,228,800 */
/* Decoder output slack: the P4 decoder may pad the output height for
 * subsampled sources; 256 KB of headroom makes the buffer un-overflowable
 * for any 1024-wide variant (worst case 1024x608 = +16 KB). */
#define OUT_BUF_BYTES  (FRAME_BYTES + 256 * 1024)
/* Largest single JPEG frame in either clip is 42,007 bytes (measured). */
#define IN_BUF_BYTES   (128 * 1024)

/* ------------------------------------------------------------------ */
/* Player state                                                        */
/* ------------------------------------------------------------------ */
static lv_obj_t *s_img;                 /* the fullscreen image widget */
static jpeg_decoder_handle_t s_decoder;
static uint8_t *s_in_buf;               /* one JPEG frame, decoder-format */
static uint8_t *s_out_buf[2];           /* double-buffered RGB565 output */
static size_t s_out_buf_size[2];        /* allocated size of each buffer */
static int s_front;                     /* index currently on screen */

/* Mutable twin of the plate descriptor: same header, data pointer swapped
 * per frame (under the display lock) to the just-decoded buffer. */
static lv_image_dsc_t s_frame_dsc = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = FRAME_W,
        .h = FRAME_H,
        .stride = FRAME_STRIDE,
    },
    .data_size = FRAME_BYTES,
    .data = NULL,
};
static bool s_frame_src_set;

/* Find the next FF xx marker pair at or after p.
 *
 * A naive scan is sound for baseline JPEG: inside entropy-coded data a
 * 0xFF byte is ALWAYS byte-stuffed with a following 0x00, so the pairs
 * FF D8 (SOI) and FF D9 (EOI) can only occur as real frame markers.
 * This exact scanner was run over both embedded blobs offline during
 * the build: it consumes each blob exactly (120 / 12 frames, zero
 * trailing bytes) and every extracted frame decodes standalone. */
static const uint8_t *scan_to_marker(const uint8_t *p, const uint8_t *end, uint8_t marker)
{
    while (p + 1 < end) {
        if (p[0] == 0xFF && p[1] == marker) {
            return p;
        }
        p++;
    }
    return NULL;
}

/* Present a decoded frame through the boot plate's image widget. */
static void present_frame(uint8_t *rgb565)
{
    bsp_display_lock(0);
    s_frame_dsc.data = rgb565;
    if (!s_frame_src_set) {
        lv_image_set_src(s_img, &s_frame_dsc);
        lv_obj_set_pos(s_img, 0, 0);
        s_frame_src_set = true;
    }
    lv_obj_invalidate(s_img);
    bsp_display_unlock();
}

/* Play one clip start to finish, paced to its frame rate. Decoder
 * errors skip the frame — they never hang the player. */
static void play_clip(const mjpeg_clip_t *clip)
{
    const size_t blob_len = (size_t)(clip->end - clip->start);
    ESP_LOGI(TAG, "clip start: %s — %lu frames @ %lu fps, %u bytes embedded",
             clip->name, (unsigned long)clip->frames,
             (unsigned long)clip->fps, (unsigned)blob_len);

    static const jpeg_decode_cfg_t decode_cfg = {
        .output_format = JPEG_DECODE_OUT_FORMAT_RGB565,
        /* KNOWN UNKNOWN (see README): BGR is the element order Espressif's
         * own decode example uses and the header pairs it with the
         * small-endian output the (proven) plate data uses. If the panel
         * shows red/blue swapped, flip this one line to
         * JPEG_DEC_RGB_ELEMENT_ORDER_RGB. */
        .rgb_order = JPEG_DEC_RGB_ELEMENT_ORDER_BGR,
    };

    const TickType_t period = pdMS_TO_TICKS(1000) / clip->fps;
    TickType_t last = xTaskGetTickCount();
    const uint8_t *cursor = clip->start;
    uint32_t idx = 0;

    while (cursor < clip->end) {
        const uint8_t *soi = scan_to_marker(cursor, clip->end, 0xD8);
        if (soi == NULL) {
            break;
        }
        const uint8_t *eoi = scan_to_marker(soi + 2, clip->end, 0xD9);
        if (eoi == NULL) {
            ESP_LOGW(TAG, "%s: no EOI after frame %lu — clip truncated?",
                     clip->name, (unsigned long)idx);
            break;
        }
        const size_t flen = (size_t)(eoi + 2 - soi);
        cursor = eoi + 2;

        if (flen > IN_BUF_BYTES) {
            ESP_LOGW(TAG, "%s frame %lu: %u bytes > input buffer — skipped",
                     clip->name, (unsigned long)idx, (unsigned)flen);
        } else {
            memcpy(s_in_buf, soi, flen);

            if (idx == 0) {
                jpeg_decode_picture_info_t info;
                if (jpeg_decoder_get_info(s_in_buf, flen, &info) == ESP_OK) {
                    ESP_LOGI(TAG, "%s: JPEG header %lux%lu",
                             clip->name, (unsigned long)info.width,
                             (unsigned long)info.height);
                }
            }

            const int back = s_front ^ 1;
            uint32_t out_size = 0;
            /* NOTE: the v5.5 header's jpeg_decoder_process takes the
             * output buffer's size as well (the online v5.5.1 doc
             * example lags the header and omits it). */
            esp_err_t err = jpeg_decoder_process(s_decoder, &decode_cfg,
                                                 s_in_buf, flen,
                                                 s_out_buf[back],
                                                 (uint32_t)s_out_buf_size[back],
                                                 &out_size);
            if (err == ESP_OK) {
                if (idx == 0) {
                    ESP_LOGI(TAG, "%s: decoded frame size %lu bytes (expect %d)",
                             clip->name, (unsigned long)out_size, FRAME_BYTES);
                }
                present_frame(s_out_buf[back]);
                s_front = back;
            } else {
                ESP_LOGW(TAG, "%s frame %lu: jpeg_decoder_process %s — skipped",
                         clip->name, (unsigned long)idx, esp_err_to_name(err));
            }
        }

        idx++;
        vTaskDelayUntil(&last, period);
    }
}

