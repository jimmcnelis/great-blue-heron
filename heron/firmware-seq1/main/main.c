static void play_idle(void)
{
    static const jpeg_decode_cfg_t decode_cfg = {
        .output_format = JPEG_DECODE_OUT_FORMAT_RGB565,
        .rgb_order = JPEG_DEC_RGB_ELEMENT_ORDER_BGR,
    };
    ESP_LOGI(TAG, "idle start — 300 ticks @ 12 fps, timing-table player");
    const TickType_t period = pdMS_TO_TICKS(1000) / 12;
    TickType_t last = xTaskGetTickCount();
    int cur_pose = -1;
    for (int t = 0; t < 300; t++) {
        const int pose = idle_sched[t];
        if (pose != cur_pose) {
            const size_t flen = (size_t)(idle_pose_end[pose] - idle_pose_start[pose]);
            if (flen > IN_BUF_BYTES) {
                ESP_LOGW(TAG, "idle tick %d: pose %d too big — skipped", t, pose);
            } else {
                memcpy(s_in_buf, idle_pose_start[pose], flen);
                const int back = s_front ^ 1;
                uint32_t out_size = 0;
                esp_err_t err = jpeg_decoder_process(s_decoder, &decode_cfg,
                                                     s_in_buf, flen,
                                                     s_out_buf[back],
                                                     (uint32_t)s_out_buf_size[back],
                                                     &out_size);
                if (err == ESP_OK) {
                    present_frame(s_out_buf[back]);
                    s_front = back;
                    cur_pose = pose;
                } else {
                    ESP_LOGW(TAG, "idle tick %d: pose %d decode %s — skipped",
                             t, pose, esp_err_to_name(err));
                }
            }
        }
        vTaskDelayUntil(&last, period);
    }
}

