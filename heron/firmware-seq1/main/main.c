/* ===== Playback order: shuffle-bag (Jimmy, 2026-11-06) =====
 * The behaviors play in a random NON-REPEATING order: a bag holding
 * each behavior once is shuffled (Fisher-Yates on the hardware RNG),
 * played through with the home rest between behaviors, then a fresh
 * bag is drawn. One guard across the seam: the new bag's first
 * behavior is never the previous bag's last, so nothing ever plays
 * twice in a row. Add STRIDE here when it ships — one row. */
typedef void (*behavior_fn_t)(void);
static const struct { const char *name; behavior_fn_t fn; } s_behaviors[] = {
    { "strike",    play_strike_behavior },
    { "idle",      play_idle },
    { "stretch",   play_stretch },
    { "preen",     play_preen },
    { "flight",    play_flight },
    { "listening", play_listening },
};
#define N_BEHAVIORS (sizeof(s_behaviors) / sizeof(s_behaviors[0]))

static void player_task(void *arg)
{
    (void)arg;

    /* Let the boot plate sit for a beat — it is the portrait's face and
     * the visual proof the display path is alive before motion starts. */
    vTaskDelay(pdMS_TO_TICKS(1500));

    uint32_t bag_no = 0;
    int prev_last = -1;
    while (1) {
        int order[N_BEHAVIORS];
        for (size_t i = 0; i < N_BEHAVIORS; i++) {
            order[i] = (int)i;
        }
        for (size_t i = N_BEHAVIORS - 1; i > 0; i--) {
            const size_t j = esp_random() % (i + 1);
            const int tmp = order[i];
            order[i] = order[j];
            order[j] = tmp;
        }
        if (prev_last >= 0 && order[0] == prev_last) {
            const size_t j = 1 + esp_random() % (N_BEHAVIORS - 1);
            const int tmp = order[0];
            order[0] = order[j];
            order[j] = tmp;
        }
        bag_no++;
        ESP_LOGI(TAG, "shuffle bag %lu: %s, %s, %s, %s, %s, %s",
                 (unsigned long)bag_no,
                 s_behaviors[order[0]].name, s_behaviors[order[1]].name,
                 s_behaviors[order[2]].name, s_behaviors[order[3]].name,
                 s_behaviors[order[4]].name, s_behaviors[order[5]].name);
        for (size_t k = 0; k < N_BEHAVIORS; k++) {
            const int b = order[k];
            s_behaviors[b].fn();
            show_rest();
            ESP_LOGI(TAG, "%s done (bag %lu, %u of %u) — resting %d ms",
                     s_behaviors[b].name, (unsigned long)bag_no,
                     (unsigned)(k + 1), (unsigned)N_BEHAVIORS, REST_HOLD_MS);
            vTaskDelay(pdMS_TO_TICKS(REST_HOLD_MS));
        }
        prev_last = order[N_BEHAVIORS - 1];
    }
}

void app_main(void)
{
    ESP_LOGI(TAG, "heron — SEQUENCE 1 player (drawn strike + rest frame)");
    ESP_LOGI(TAG, "embedded payload: seq1 %u bytes + rest %u bytes",
             (unsigned)(seq1_mjpeg_end - seq1_mjpeg_start),
             (unsigned)(rest_jpg_end - rest_jpg_start));

    /* Panel + LVGL port + GT911 touch, all initialised by the BSP —
     * identical display path to first light (the board sits rotated
     * 180° in its case and reads upright exactly as configured here;
     * do not add rotation or mirroring). */
    lv_display_t *disp = bsp_display_start();
    if (disp == NULL) {
        ESP_LOGE(TAG, "bsp_display_start() failed — no display");
        return;
    }
    ESP_ERROR_CHECK(bsp_display_brightness_set(100));

    bsp_display_lock(0);
    lv_obj_t *scr = lv_screen_active();
    lv_obj_remove_flag(scr, LV_OBJ_FLAG_SCROLLABLE);
    s_img = lv_image_create(scr);
    lv_image_set_src(s_img, &alert_plate_img);
    lv_obj_set_pos(s_img, 0, 0);
    lv_obj_remove_flag(s_img, LV_OBJ_FLAG_SCROLLABLE);
    bsp_display_unlock();

    ESP_LOGI(TAG, "boot plate on screen (%dx%d RGB565)", BSP_LCD_H_RES, BSP_LCD_V_RES);

    /* --- Hardware JPEG decoder + buffers --------------------------- */
    jpeg_decode_engine_cfg_t eng_cfg = {
        .intr_priority = 0,
        .timeout_ms = 100,
    };
    esp_err_t err = jpeg_new_decoder_engine(&eng_cfg, &s_decoder);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "jpeg_new_decoder_engine: %s — staying on the still plate",
                 esp_err_to_name(err));
        while (1) {
            vTaskDelay(pdMS_TO_TICKS(1000));
        }
    }

    jpeg_decode_memory_alloc_cfg_t in_alloc_cfg = {
        .buffer_direction = JPEG_DEC_ALLOC_INPUT_BUFFER,
    };
    jpeg_decode_memory_alloc_cfg_t out_alloc_cfg = {
        .buffer_direction = JPEG_DEC_ALLOC_OUTPUT_BUFFER,
    };
    size_t in_size = 0;
    s_in_buf = jpeg_alloc_decoder_mem(IN_BUF_BYTES, &in_alloc_cfg, &in_size);
    s_out_buf[0] = jpeg_alloc_decoder_mem(OUT_BUF_BYTES, &out_alloc_cfg, &s_out_buf_size[0]);
    s_out_buf[1] = jpeg_alloc_decoder_mem(OUT_BUF_BYTES, &out_alloc_cfg, &s_out_buf_size[1]);
    if (s_in_buf == NULL || s_out_buf[0] == NULL || s_out_buf[1] == NULL) {
        ESP_LOGE(TAG, "decoder buffer allocation failed — staying on the still plate");
        while (1) {
            vTaskDelay(pdMS_TO_TICKS(1000));
        }
    }
    ESP_LOGI(TAG, "decoder buffers: in %u B, out %u + %u B (PSRAM)",
             (unsigned)in_size, (unsigned)s_out_buf_size[0],
             (unsigned)s_out_buf_size[1]);

    s_assets_ok = assets_init();

    xTaskCreate(player_task, "heron_player", 8192, NULL, 5, NULL);
    ESP_LOGI(TAG, "player task running — idle loop is live");
}
