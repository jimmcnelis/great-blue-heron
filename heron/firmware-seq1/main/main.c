/* Flight assets live in the 'assets' data partition (esptool caps a
 * single app-image flash segment at 16 MB, and the set's embedded
 * rodata would exceed it with flight included). assets.bin layout:
 * a 64 KB header page (magic + per-asset offset/length), then each
 * asset at a 64 KB boundary. The player mmaps one asset at a time. */
#include "esp_partition.h"
#include "esp_random.h"
#define ASSETS_MAGIC 0x54534148u /* 'HAST' little-endian */
enum { ASSET_FLIGHT_OUT = 0, ASSET_FLIGHT_HOME = 1, ASSET_PLATE = 2, ASSET_COUNT = 3 };
static const esp_partition_t *s_assets_part;
static uint32_t s_asset_off[ASSET_COUNT];
static uint32_t s_asset_len[ASSET_COUNT];
static bool s_assets_ok;

static bool assets_init(void)
{
    s_assets_part = esp_partition_find_first(ESP_PARTITION_TYPE_DATA,
                                             ESP_PARTITION_SUBTYPE_ANY, "assets");
    if (s_assets_part == NULL) {
        ESP_LOGW(TAG, "assets partition not found — flight disabled");
        return false;
    }
    esp_partition_mmap_handle_t h;
    const void *p = NULL;
    if (esp_partition_mmap(s_assets_part, 0, 64 * 1024,
                           ESP_PARTITION_MMAP_DATA, &p, &h) != ESP_OK) {
        ESP_LOGW(TAG, "assets header mmap failed — flight disabled");
        return false;
    }
    const uint32_t *hdr = (const uint32_t *)p;
    bool ok = (hdr[0] == ASSETS_MAGIC);
    if (ok) {
        for (int i = 0; i < ASSET_COUNT; i++) {
            s_asset_off[i] = hdr[1 + 2 * i];
            s_asset_len[i] = hdr[2 + 2 * i];
            if (s_asset_off[i] + s_asset_len[i] > s_assets_part->size) {
                ok = false;
            }
        }
    }
    esp_partition_munmap(h);
    if (!ok) {
        ESP_LOGW(TAG, "assets header invalid — flight disabled");
        return false;
    }
    ESP_LOGI(TAG, "assets ready: out %lu B @ %lu, home %lu B @ %lu, plate %lu B @ %lu",
             (unsigned long)s_asset_len[0], (unsigned long)s_asset_off[0],
             (unsigned long)s_asset_len[1], (unsigned long)s_asset_off[1],
             (unsigned long)s_asset_len[2], (unsigned long)s_asset_off[2]);
    return true;
}

/* Map one asset; caller munmaps the returned handle when done. */
static const uint8_t *asset_map(int idx, esp_partition_mmap_handle_t *out_h)
{
    const void *p = NULL;
    if (esp_partition_mmap(s_assets_part, s_asset_off[idx], s_asset_len[idx],
                           ESP_PARTITION_MMAP_DATA, &p, out_h) != ESP_OK) {
        ESP_LOGW(TAG, "asset %d mmap failed", idx);
        return NULL;
    }
    return (const uint8_t *)p;
}

