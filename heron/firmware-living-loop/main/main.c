/*
 * heron living loop — STAGE A (motion proof).
 *
 * Boot shows the approved alert plate (same first-light path), then a
 * player task loops the two accepted idle cycles forever, alternating:
 * idle1 (generated breath, 10 s) -> idle2 (procedural loop, 1 s) -> ...
 * Both clips start and end on the alert stance, so the cuts are clean.
 * No scheduler, no other behaviors — that is Stage B, gated on this
 * proof passing on the real board.
 *
 * Board : Waveshare ESP32-P4-WIFI6-Touch-LCD-7B (Rev1.1), 1024x600 MIPI-DSI
 * BSP   : waveshare/esp32_p4_wifi6_touch_lcd_7b 1.0.4 (main/idf_component.yml)
 * Decode: ESP32-P4 hardware JPEG decoder (esp_driver_jpeg), YUV422 MJPEG
 *         frames -> RGB565, presented through the same LVGL image widget
 *         that shows the boot plate.
 *
 * The clips are embedded with CMake EMBED_FILES (see main/CMakeLists.txt):
 *   idle1.mjpeg  attempt1.mp4 @ 12 fps, q9, yuvj422p — 120 frames, 10.0 s
 *   idle2.mjpeg  attempt2.mp4 @ 12 fps, q9, yuvj422p —  12 frames,  1.0 s
 */
#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_err.h"
#include "esp_log.h"

#include "lvgl.h"
#include "bsp/esp32_p4_wifi6_touch_lcd_7b.h"
#include "bsp/display.h"
#include "driver/jpeg_decode.h"

#include "alert_plate_img.h"

static const char *TAG = "heron_living_loop";

/* ------------------------------------------------------------------ */
/* Embedded MJPEG clips (symbols generated by EMBED_FILES)             */
/* ------------------------------------------------------------------ */
extern const uint8_t idle1_mjpeg_start[] asm("_binary_idle1_mjpeg_start");
extern const uint8_t idle1_mjpeg_end[] asm("_binary_idle1_mjpeg_end");
extern const uint8_t idle2_mjpeg_start[] asm("_binary_idle2_mjpeg_start");
extern const uint8_t idle2_mjpeg_end[] asm("_binary_idle2_mjpeg_end");

typedef struct {
    const char *name;
    const uint8_t *start;
    const uint8_t *end;
    uint32_t frames; /* verified offline by the SOI/EOI scanner */
    uint32_t fps;
} mjpeg_clip_t;

static const mjpeg_clip_t s_clips[] = {
    { "idle1 (attempt1, generated breath)", idle1_mjpeg_start, idle1_mjpeg_end, 120, 12 },
    { "idle2 (attempt2, procedural loop)",  idle2_mjpeg_start, idle2_mjpeg_end,  12, 12 },
};

/* ------------------------------------------------------------------ */
/* Frame geometry                                                      */
/* ------------------------------------------------------------------ */
#define FRAME_W        1024
#define FRAME_H        600
#define FRAME_STRIDE   (FRAME_W * 2)              /* RGB565 bytes per row */
#define FRAME_BYTES    (FRAME_W * FRAME_H * 2)    /* 1,228,800 */
/* Decoder output slack: the P4 decoder may pad the output height for
 * subsampled sources; 256 KB of headroom makes the buffer un-overflowable
 * for any 1024-wide variant (worst case 1024x608 = +16 KB). */
#define OUT_BUF_BYTES  (FRAME_BYTES + 256 * 1024)
/* Largest single JPEG frame in either clip is 42,007 bytes (measured). */
#define IN_BUF_BYTES   (128 * 1024)

/* ------------------------------------------------------------------ */
/* Player state                                                        */
/* ------------------------------------------------------------------ */
static lv_obj_t *s_img;                 /* the fullscreen image widget */
static jpeg_decoder_handle_t s_decoder;
static uint8_t *s_in_buf;               /* one JPEG frame, decoder-format */
static uint8_t *s_out_buf[2];           /* double-buffered RGB565 output */
static size_t s_out_buf_size[2];        /* allocated size of each buffer */
static int s_front;                     /* index currently on screen */

/* Mutable twin of the plate descriptor: same header, data pointer swapped
 * per frame (under the display lock) to the just-decoded buffer. */
static lv_image_dsc_t s_frame_dsc = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = FRAME_W,
        .h = FRAME_H,
        .stride = FRAME_STRIDE,
    },
    .data_size = FRAME_BYTES,
    .data = NULL,
};
static bool s_frame_src_set;

/* Find the next FF xx marker pair at or after p.
 *
 * A naive scan is sound for baseline JPEG: inside entropy-coded data a
 * 0xFF byte is ALWAYS byte-stuffed with a following 0x00, so the pairs
 * FF D8 (SOI) and FF D9 (EOI) can only occur as real frame markers.
 * This exact scanner was run over both embedded blobs offline during
 * the build: it consumes each blob exactly (120 / 12 frames, zero
 * trailing bytes) and every extracted frame decodes standalone. */
static const uint8_t *scan_to_marker(const uint8_t *p, const uint8_t *end, uint8_t marker)
{
    while (p + 1 < end) {
        if (p[0] == 0xFF && p[1] == marker) {
            return p;
        }
        p++;
    }
    return NULL;
}

/* Present a decoded frame through the boot plate's image widget. */
static void present_frame(uint8_t *rgb565)
{
    bsp_display_lock(0);
    s_frame_dsc.data = rgb565;
    if (!s_frame_src_set) {
        lv_image_set_src(s_img, &s_frame_dsc);
        lv_obj_set_pos(s_img, 0, 0);
        s_frame_src_set = true;
    }
    lv_obj_invalidate(s_img);
    bsp_display_unlock();
}

/* Play one clip start to finish, paced to its frame rate. Decoder
 * errors skip the frame — they never hang the player. */
static void play_clip(const mjpeg_clip_t *clip)
{
    const size_t blob_len = (size_t)(clip->end - clip->start);
    ESP_LOGI(TAG, "clip start: %s — %lu frames @ %lu fps, %u bytes embedded",
             clip->name, (unsigned long)clip->frames,
             (unsigned long)clip->fps, (unsigned)blob_len);

    static const jpeg_decode_cfg_t decode_cfg = {
        .output_format = JPEG_DECODE_OUT_FORMAT_RGB565,
        /* KNOWN UNKNOWN (see README): BGR is the element order Espressif's
         * own decode example uses and the header pairs it with the
         * small-endian output the (proven) plate data uses. If the panel
         * shows red/blue swapped, flip this one line to
         * JPEG_DEC_RGB_ELEMENT_ORDER_RGB. */
        .rgb_order = JPEG_DEC_RGB_ELEMENT_ORDER_BGR,
    };

    const TickType_t period = pdMS_TO_TICKS(1000) / clip->fps;
    TickType_t last = xTaskGetTickCount();
    const uint8_t *cursor = clip->start;
    uint32_t idx = 0;

    while (cursor < clip->end) {
        const uint8_t *soi = scan_to_marker(cursor, clip->end, 0xD8);
        if (soi == NULL) {
            break;
        }
        const uint8_t *eoi = scan_to_marker(soi + 2, clip->end, 0xD9);
        if (eoi == NULL) {
            ESP_LOGW(TAG, "%s: no EOI after frame %lu — clip truncated?",
                     clip->name, (unsigned long)idx);
            break;
        }
        const size_t flen = (size_t)(eoi + 2 - soi);
        cursor = eoi + 2;

        if (flen > IN_BUF_BYTES) {
            ESP_LOGW(TAG, "%s frame %lu: %u bytes > input buffer — skipped",
                     clip->name, (unsigned long)idx, (unsigned)flen);
        } else {
            memcpy(s_in_buf, soi, flen);

            if (idx == 0) {
                jpeg_decode_picture_info_t info;
                if (jpeg_decoder_get_info(s_in_buf, flen, &info) == ESP_OK) {
                    ESP_LOGI(TAG, "%s: JPEG header %lux%lu",
                             clip->name, (unsigned long)info.width,
                             (unsigned long)info.height);
                }
            }

            const int back = s_front ^ 1;
            uint32_t out_size = 0;
            /* NOTE: the v5.5 header's jpeg_decoder_process takes the
             * output buffer's size as well (the online v5.5.1 doc
             * example lags the header and omits it). */
            esp_err_t err = jpeg_decoder_process(s_decoder, &decode_cfg,
                                                 s_in_buf, flen,
                                                 s_out_buf[back],
                                                 (uint32_t)s_out_buf_size[back],
                                                 &out_size);
            if (err == ESP_OK) {
                if (idx == 0) {
                    ESP_LOGI(TAG, "%s: decoded frame size %lu bytes (expect %d)",
                             clip->name, (unsigned long)out_size, FRAME_BYTES);
                }
                present_frame(s_out_buf[back]);
                s_front = back;
            } else {
                ESP_LOGW(TAG, "%s frame %lu: jpeg_decoder_process %s — skipped",
                         clip->name, (unsigned long)idx, esp_err_to_name(err));
            }
        }

        idx++;
        vTaskDelayUntil(&last, period);
    }
}

static void player_task(void *arg)
{
    (void)arg;

    /* Let the boot plate sit for a beat — it is the portrait's face and
     * the visual proof the display path is alive before motion starts. */
    vTaskDelay(pdMS_TO_TICKS(1500));

    uint32_t pass = 0;
    while (1) {
        for (size_t i = 0; i < sizeof(s_clips) / sizeof(s_clips[0]); i++) {
            play_clip(&s_clips[i]);
        }
        pass++;
        ESP_LOGI(TAG, "living loop pass %lu complete (idle1 + idle2)",
                 (unsigned long)pass);
    }
}

void app_main(void)
{
    ESP_LOGI(TAG, "heron living loop — STAGE A motion proof");
    ESP_LOGI(TAG, "embedded MJPEG payload: %u bytes (idle1 %u + idle2 %u)",
             (unsigned)((idle1_mjpeg_end - idle1_mjpeg_start) +
                        (idle2_mjpeg_end - idle2_mjpeg_start)),
             (unsigned)(idle1_mjpeg_end - idle1_mjpeg_start),
             (unsigned)(idle2_mjpeg_end - idle2_mjpeg_start));

    /* Panel + LVGL port + GT911 touch, all initialised by the BSP —
     * identical display path to first light (the board sits rotated
     * 180° in its case and reads upright exactly as configured here;
     * do not add rotation or mirroring). */
    lv_display_t *disp = bsp_display_start();
    if (disp == NULL) {
        ESP_LOGE(TAG, "bsp_display_start() failed — no display");
        return;
    }
    ESP_ERROR_CHECK(bsp_display_brightness_set(100));

    bsp_display_lock(0);
    lv_obj_t *scr = lv_screen_active();
    lv_obj_remove_flag(scr, LV_OBJ_FLAG_SCROLLABLE);
    s_img = lv_image_create(scr);
    lv_image_set_src(s_img, &alert_plate_img);
    lv_obj_set_pos(s_img, 0, 0);
    lv_obj_remove_flag(s_img, LV_OBJ_FLAG_SCROLLABLE);
    bsp_display_unlock();

    ESP_LOGI(TAG, "boot plate on screen (%dx%d RGB565)", BSP_LCD_H_RES, BSP_LCD_V_RES);

    /* --- Hardware JPEG decoder + buffers --------------------------- */
    jpeg_decode_engine_cfg_t eng_cfg = {
        .intr_priority = 0,
        .timeout_ms = 100,
    };
    esp_err_t err = jpeg_new_decoder_engine(&eng_cfg, &s_decoder);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "jpeg_new_decoder_engine: %s — staying on the still plate",
                 esp_err_to_name(err));
        while (1) {
            vTaskDelay(pdMS_TO_TICKS(1000));
        }
    }

    jpeg_decode_memory_alloc_cfg_t in_alloc_cfg = {
        .buffer_direction = JPEG_DEC_ALLOC_INPUT_BUFFER,
    };
    jpeg_decode_memory_alloc_cfg_t out_alloc_cfg = {
        .buffer_direction = JPEG_DEC_ALLOC_OUTPUT_BUFFER,
    };
    size_t in_size = 0;
    s_in_buf = jpeg_alloc_decoder_mem(IN_BUF_BYTES, &in_alloc_cfg, &in_size);
    s_out_buf[0] = jpeg_alloc_decoder_mem(OUT_BUF_BYTES, &out_alloc_cfg, &s_out_buf_size[0]);
    s_out_buf[1] = jpeg_alloc_decoder_mem(OUT_BUF_BYTES, &out_alloc_cfg, &s_out_buf_size[1]);
    if (s_in_buf == NULL || s_out_buf[0] == NULL || s_out_buf[1] == NULL) {
        ESP_LOGE(TAG, "decoder buffer allocation failed — staying on the still plate");
        while (1) {
            vTaskDelay(pdMS_TO_TICKS(1000));
        }
    }
    ESP_LOGI(TAG, "decoder buffers: in %u B, out %u + %u B (PSRAM)",
             (unsigned)in_size, (unsigned)s_out_buf_size[0],
             (unsigned)s_out_buf_size[1]);

    xTaskCreate(player_task, "heron_player", 8192, NULL, 5, NULL);
    ESP_LOGI(TAG, "player task running — idle loop is live");
}
