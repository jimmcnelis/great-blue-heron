#!/usr/bin/env python3
"""
png_to_lvgl_rgb565.py — convert a PNG into an LVGL v9 image C array (RGB565).

Written for the heron first-light firmware (Waveshare ESP32-P4-WIFI6-Touch-LCD-7B,
BSP waveshare/esp32_p4_wifi6_touch_lcd_7b 1.0.4, which pairs with LVGL v9 via
espressif/esp_lvgl_port ^2). The generated descriptor uses LVGL 9's
lv_image_dsc_t with LV_COLOR_FORMAT_RGB565.

Pixel packing (matches LVGL's own image converter output for RGB565):
  value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
  stored little-endian (low byte first), row-major, stride = width * 2.
This matches the BSP setting BSP_LCD_BIGENDIAN = 0 -> esp_lvgl_port swap_bytes=false.

Usage:
  python3 png_to_lvgl_rgb565.py INPUT.png OUTPUT.c SYMBOL_NAME [HEADER_NAME]

Example (regenerate the plate):
  python3 tools/png_to_lvgl_rgb565.py \
      ../art2/plates-fresh/eye-first/final/alert_legfix_approved.png \
      main/alert_plate_img.c alert_plate_img alert_plate_img.h

The script refuses to write anything if the checks fail, and prints the
first/last-row RGB565 words so a human can eyeball them against the source.
"""

import sys
from PIL import Image

BYTES_PER_LINE = 32


def main() -> int:
    if len(sys.argv) not in (4, 5):
        print(__doc__)
        return 2
    src_path, out_path, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
    header_name = sys.argv[4] if len(sys.argv) == 5 else f"{symbol}.h"

    im = Image.open(src_path)
    if im.mode != "RGB":
        im = im.convert("RGB")
    w, h = im.size
    px = im.load()

    data = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            data.append(v & 0xFF)        # little-endian: low byte first
            data.append((v >> 8) & 0xFF)

    expected = w * h * 2
    assert len(data) == expected, f"data size {len(data)} != {expected}"

    def row_words(y):
        base = y * w * 2
        return [data[base + 2 * i] | (data[base + 2 * i + 1] << 8) for i in (0, 1, 2, w - 2, w - 1)]

    print(f"source : {src_path} ({w}x{h})")
    print(f"output : {out_path}, symbol {symbol}")
    print(f"bytes  : {len(data)} (= {w}*{h}*2 = {expected})")
    print(f"row 0 words [0,1,2,{w-2},{w-1}]: {[hex(v) for v in row_words(0)]}")
    print(f"row {h-1} words [0,1,2,{w-2},{w-1}]: {[hex(v) for v in row_words(h - 1)]}")

    lines = []
    lines.append("/*")
    lines.append(f" * {symbol} — LVGL v9 image, RGB565, {w}x{h}.")
    lines.append(f" * Generated by tools/png_to_lvgl_rgb565.py from: {src_path}")
    lines.append(" * Do not edit by hand; re-run the converter instead.")
    lines.append(" */")
    lines.append(f'#include "{header_name}"')
    lines.append("")
    lines.append(f"static const uint8_t {symbol}_map[] __attribute__((aligned(4))) = {{")
    for y in range(h):
        lines.append(f"    /* row {y} */")
        base = y * w * 2
        row = data[base:base + w * 2]
        for off in range(0, len(row), BYTES_PER_LINE):
            chunk = row[off:off + BYTES_PER_LINE]
            lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    lines.append("};")
    lines.append("")
    lines.append(f"const lv_image_dsc_t {symbol} = {{")
    lines.append("    .header = {")
    lines.append("        .magic = LV_IMAGE_HEADER_MAGIC,")
    lines.append("        .cf = LV_COLOR_FORMAT_RGB565,")
    lines.append("        .flags = 0,")
    lines.append(f"        .w = {w},")
    lines.append(f"        .h = {h},")
    lines.append(f"        .stride = {w * 2},")
    lines.append("    },")
    lines.append(f"    .data_size = {len(data)},")
    lines.append(f"    .data = {symbol}_map,")
    lines.append("};")
    lines.append("")
    lines.append(f"_Static_assert(sizeof({symbol}_map) == {expected},")
    lines.append(f"               \"{symbol}: pixel data must be width*height*2 bytes\");")
    lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
