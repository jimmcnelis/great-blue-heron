/*
 * heron living loop — STAGE B PLAYER (DRAFT, gate-held — see
 * STAGE_B_MANIFEST.md). This file is NOT referenced by main/CMakeLists.txt
 * and does not change the Stage A build in any way. It is the complete
 * Stage B player, written against the Stage A proven decode/display path,
 * ready to become main/main.c the moment a storage option is chosen:
 *
 *   - If clips stay EMBEDDED (flash subset options), the extern symbol
 *     table below is already correct: name the .mjpeg files in
 *     main/CMakeLists.txt EMBED_FILES exactly as the symbols expect.
 *   - If clips move to microSD (recommended option A), only the frame
 *     source changes: replace the blob cursor with a file reader that
 *     yields the same SOI..EOI spans. Decode, present, scheduler and
 *     crossfade code are untouched by that swap.
 *
 * What Stage B adds over Stage A (main/main.c, proven on the board):
 *   1. The shuffle-bag scheduler, ported from living_loop_scheduler.py:
 *      tickets preen x3, stride x3, strike x2, stretch x2, miss x2,
 *      flight x1, courtship x1 (14 tickets; nightstalk excluded — no
 *      light sensor in the kit). Draws WITHOUT replacement; on refill
 *      the bag is reshuffled until its first ticket differs from the
 *      behavior that just played. Randomized idle holds of 20–90 s
 *      (idle1 10 s blocks sprinkled into idle2 tiles, unit order
 *      shuffled) open the loop and sit between every draw. Every cycle
 *      starts/ends on the shared alert stance.
 *   2. A ~0.33 s CROSSFADE at every unit join (Jimmy's catch on Stage A:
 *      generated clips and the plate-warp idle are different renderings
 *      and hard cuts pop). The first 4 frames of an incoming unit are
 *      blended against the last shown frame in a dedicated blend buffer;
 *      the shown buffer is never written while LVGL may be scanning it.
 *   3. Randomness from esp_random(); the boot seed value is logged, and
 *      every draw / hold / reshuffle is logged on serial.
 *
 * Board/display/decoder configuration is byte-for-byte Stage A:
 * BSP 1.0.4 display path, esp_driver_jpeg YUV422 -> RGB565,
 * JPEG_DEC_RGB_ELEMENT_ORDER_BGR (proven correct on the panel).
 */
